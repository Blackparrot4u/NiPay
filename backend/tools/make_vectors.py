"""Writes shared/vectors.json: cross-language test vectors for the ID checker, mines and Ed25519.

The seed and keys below are PUBLIC TEST CONSTANTS used only to make this fixture. They are not
the server's seed or key (those are generated on first run into gitignored backend/data/)."""
import base64
import json
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from nacl.signing import SigningKey

from nipay.core.idsystem import ALPHA, Bank, check_landmines, check_tower, make_id, phone_check, sign_handover, sign_receipt
from nipay.core.wallet import HardwareCounter, Wallet, audit_mines, mine_recipe, rules_blob

b64 = lambda b: base64.b64encode(b).decode()
SEED, KEY, DEV = b"TEST-VECTOR-SEED-NOT-A-REAL-ONE", b"TEST-VECTOR-KEY--NOT-A-REAL-ONE!", b"TEST-VECTOR-DEVICE-NOT-REAL-ONE!"
M = "2026-11"
bank = Bank(seed=SEED, signing=SigningKey(KEY))
r = bank.rules(M)
rec = mine_recipe(SEED, M)
rng = random.Random(5)
ids = [make_id(r) for _ in range(300)]
sig = lambda p: bank.signing.sign(f"{M}|{p}".encode()).signature
checks = []
for p in ids[:20]:
    checks.append({"pid": p, "sig": b64(sig(p)), "block": False})
for p in ids[20:25]:
    q = ("z" if p[0] != "z" else "y") + p[1:]
    checks.append({"pid": q, "sig": b64(sig(p)), "block": False})            # edited ID, real signature
for p in ids[25:30]:
    checks.append({"pid": p, "sig": b64(bytes(64)), "block": False})        # random signature
for _ in range(20):
    q = "".join(rng.choice(ALPHA) for _ in range(20))
    checks.append({"pid": q, "sig": b64(bytes(64)), "block": False})
checks.append({"pid": ids[30], "sig": b64(sig(ids[30])), "block": True})     # flagged by a notice
for c in checks:
    c["expect"] = phone_check(c["pid"], __import__("base64").b64decode(c["sig"]), r, bank.public,
                              blocklist=frozenset({c["pid"]}) if c["block"] else frozenset())

w = Wallet(rec, ids[:60], ids[0], HardwareCounter())
w.arm(15)
mines0 = [list(m) for m in w.mines]
points0 = list(w.points)
a1 = list(w.spend(25))
points1 = list(w.points)
fill_in = ids[100:160]
w2 = Wallet(rec, ids[:60], ids[0], HardwareCounter()); w2.arm(15); w2.spend(10)
before = (list(w2.points), [list(m) for m in w2.mines])
filled = w2.receive_fill(fill_in)
w3 = Wallet(rec, ids[:60], ids[0], HardwareCounter()); w3.arm(15)
fake = Wallet(rec, ids[:60], ids[0], HardwareCounter()); fake.arm(15); fake.mines[0] = tuple(ids[200:203]); fake.points += list(fake.mines[0])
dev = SigningKey(DEV)
out = {
    "note": "generated by backend/tools/make_vectors.py with public test constants; not the real server seed or key",
    "month": M, "bank_pub": b64(bytes(bank.public)),
    "rules_blob": b64(rules_blob(r)), "rules_sig": b64(bank.signing.sign(rules_blob(r)).signature),
    "recipe": {"month": M, "pos": list(rec.positions), "t": rec.target},
    "checks": checks,
    "mines": {"ids": ids[:60], "control": ids[0], "found": mines0, "points_after_arm": points0, "spend25": a1, "points_after_spend": points1,
              "fill": {"points_before": before[0], "mines_before": before[1], "incoming": fill_in, "points_after": list(w2.points),
                       "mines_after": [list(m) for m in w2.mines], "filled": filled},
              "audit_ok": audit_mines(w3), "audit_fake": {"points": list(fake.points), "mines": [list(m) for m in fake.mines], "result": audit_mines(fake)}},
    "device": {"seed_hex": DEV.hex(), "pub": b64(bytes(dev.verify_key)),
               "handover": {"month": M, "pid": ids[0], "to": "+919000000002", "sig": b64(sign_handover(dev, M, ids[0], "+919000000002"))},
               "receipt": {"month": M, "pid": ids[0], "from": "+919000000001", "sig": b64(sign_receipt(dev, M, ids[0], "+919000000001"))}},
}
Path(__file__).resolve().parent.parent.parent.joinpath("shared", "vectors.json").write_text(json.dumps(out, indent=1))
print("wrote shared/vectors.json", len(checks), "checks;", {c["expect"] for c in checks})
